#!/bin/bash
# The Competitive HUD radar's picture made on the GPU (code/renderer_metal/shaders/tr_mtl_radar.metal) against the
# UI's own paint of it (RM_Paint, code/client/cl_uicomp.cpp), byte for byte (docs/METAL_PORT_PLAN.md §6, sessions 89
# and 93). port/radartest.mm is built into build.noindex/radartest/ with RM_Paint, the floor list's types
# (tr_public.h), Com_Clamp (q_shared.c) and the kernels' parameters (tr_mtl.m) taken out of the source as they are,
# compiled with the game's floating-point flags; the shader is compiled as the game's build compiles it. Offline, no
# window, no game data:
#   port/radartest.sh                   alpha, lists and real (the floor lists the game dumped, if any): all must pass
#   port/radartest.sh alpha             every float height distance in [60, 125] by every shade (~10 s)
#   port/radartest.sh lists [n]         n made-up floor lists (60), whole pictures and heights' changes
#   port/radartest.sh real [file [heights]]   the dumped floor lists (build.noindex/radartest/floors-*.bin, each with
#                                       its .heights beside it), at every texel count they can have
#   port/radartest.sh bench [file [heights]]  the GPU's time of the whole picture and of a height's change
# RADARTEST_METAL=<file.metal> tests or benches another shader (a variant) in place of the game's.
# In the game (a window: check that nobody is at the machine first, CLAUDE.md):
#   port/radartest.sh build             the check flavor radarchk (build.noindex/radarchk-install): the work tree
#                                       plus port/radarchk_patch.py: every picture the renderer makes read back
#                                       and compared with RM_Paint's ("RADARCHK" lines in the console)
#   port/radartest.sh game [demo] [engine args]   radarchk on a demo as a timedemo (demo0007: home.noindex/main/demos),
#                                       its floor lists and heights dumped into build.noindex/radartest/
set -euo pipefail
source "$(dirname "$0")/env.sh"

OUT="$OMM_BUILD/radartest"
mkdir -p "$OUT"
SHADER="${RADARTEST_METAL:-$OMM_ROOT/code/renderer_metal/shaders/tr_mtl_radar.metal}"

# one block of a source file, from the line matching $2 to the first after it matching $3: exactly one
take() {
	local file="$OMM_ROOT/$1" text
	text=$(awk -v a="$2" -v b="$3" '$0 ~ a { n++; on = 1 } on { print } on && $0 ~ b { on = 0 } END { if (n != 1) exit 1 }' "$file") \
		|| { echo "radartest.sh: '$2' isn't in $1 exactly once" >&2; exit 2; }
	[ -n "$text" ] || { echo "radartest.sh: nothing taken from $1" >&2; exit 2; }
	printf '// %s\n%s\n\n' "$1" "$text"
}

build() {
	local inc="$OUT/radartest_src.inc.new"
	{
		echo "// Generated by port/radartest.sh from the game's source. Do not edit."
		take code/renderercommon/tr_public.h "^// Added: the Competitive HUD radar's floors" "^} radar2D_t;"
		take code/renderer_metal/tr_mtl.m "^// the Competitive HUD's radar picture [(]mbRadarImage[)]" "^} mbRadarParams_t;"
		take code/qcommon/q_shared.c "^float Com_Clamp[(]" "^}"
		take code/client/cl_uicomp.cpp "^static void RM_Paint[(]" "^}"
	} > "$inc"
	cmp -s "$inc" "$OUT/radartest_src.inc" 2>/dev/null && rm "$inc" || mv "$inc" "$OUT/radartest_src.inc"
	if [ ! -x "$OUT/radartest" ] || [ -n "$(find "$OMM_PORT/radartest.mm" "$OUT/radartest_src.inc" "$0" -newer "$OUT/radartest")" ]; then
		# the game's flags for cl_uicomp.cpp (build.ninja) that touch its floating point: -O3, no fast math, so clang
		# contracts a + b * c into a fused multiply-add as there
		clang++ -std=gnu++17 -O3 -arch arm64 -mmacosx-version-min=26.0 -fno-strict-aliasing -fobjc-arc -x objective-c++ \
			-Wall -Wno-unused-function -I "$OUT" "$OMM_PORT/radartest.mm" -framework Metal -framework Foundation -o "$OUT/radartest"
	fi
	# the shader as cmake/utils/metallib.cmake compiles it
	local lib="$OUT/radar.metallib"
	if [ ! -f "$lib" ] || [ "$SHADER" -nt "$lib" ] || [ "$(cat "$OUT/radar.metallib.src" 2>/dev/null)" != "$SHADER" ]; then
		omm_mount_metal
		"$OMM_METAL_BIN/metal" -std=metal4.0 -target air64-apple-macos26.0 -O3 -fpreserve-invariance -Wall -Werror \
			-fmodules-cache-path="$OUT/module-cache" -c "$SHADER" -o "$OUT/radar.air"
		"$OMM_METAL_BIN/metallib" "$OUT/radar.air" -o "$lib"
		echo "$SHADER" > "$OUT/radar.metallib.src"
	fi
}

real() {	# [file [heights]]: the given one, else every dump
	local status=0 f
	if [ $# -gt 0 ]; then
		"$OUT/radartest" "$OUT/radar.metallib" real "$@" || status=1
		return $status
	fi
	for f in "$OUT"/floors-*.bin; do
		[ -e "$f" ] || { echo "real: no dumped floor lists (port/radartest.sh game makes them)"; return 0; }
		"$OUT/radartest" "$OUT/radar.metallib" real "$f" "${f%.bin}.heights" || status=1
	done
	return $status
}

mode=${1:-all}
[ $# -gt 0 ] && shift
case "$mode" in
	all)
		build
		status=0
		"$OUT/radartest" "$OUT/radar.metallib" alpha || status=1
		"$OUT/radartest" "$OUT/radar.metallib" lists || status=1
		real || status=1
		[ $status = 0 ] && echo "radartest: passed" || echo "radartest: FAILED"
		exit $status
		;;
	alpha|lists)
		build
		"$OUT/radartest" "$OUT/radar.metallib" "$mode" "$@"
		;;
	real)
		build
		real "$@"
		;;
	bench)
		build
		if [ $# -gt 0 ]; then
			"$OUT/radartest" "$OUT/radar.metallib" bench "$@"
		else
			for f in "$OUT"/floors-*.bin; do
				[ -e "$f" ] || { echo "bench: no dumped floor lists (port/radartest.sh game makes them)"; exit 1; }
				"$OUT/radartest" "$OUT/radar.metallib" bench "$f" "${f%.bin}.heights"
			done
		fi
		;;
	build)
		SRC_DIR="$OMM_BUILD/radarchk-src"
		rm -rf "$SRC_DIR"
		mkdir -p "$SRC_DIR"
		git -C "$OMM_ROOT" archive HEAD | tar -x -C "$SRC_DIR"
		{ git -C "$OMM_ROOT" diff --name-only HEAD; git -C "$OMM_ROOT" ls-files --others --exclude-standard -- code cmake; } | while read -r f; do
			if [ -f "$OMM_ROOT/$f" ]; then cp "$OMM_ROOT/$f" "$SRC_DIR/$f"; else rm -f "$SRC_DIR/$f"; fi
		done
		python3 -I "$OMM_PORT/radarchk_patch.py" "$SRC_DIR"
		export GIT_CEILING_DIRECTORIES="$OMM_BUILD"
		omm_mount_metal
		"$OMM_CMAKE" -S "$SRC_DIR" -B "$OMM_BUILD/radarchk" -G Ninja \
			-DCMAKE_MAKE_PROGRAM="$OMM_NINJA" \
			-DBISON_EXECUTABLE="$OMM_BISON" \
			-DCMAKE_BUILD_TYPE=Release \
			-DCMAKE_INSTALL_PREFIX="$OMM_BUILD/radarchk-install" >/dev/null
		"$OMM_CMAKE" --build "$OMM_BUILD/radarchk" -j"$(sysctl -n hw.ncpu)"
		"$OMM_CMAKE" --install "$OMM_BUILD/radarchk" >/dev/null
		echo "radartest.sh: radarchk installed in $OMM_BUILD/radarchk-install"
		;;
	game)
		DEMO="${1:-demo0007}"
		[ $# -gt 0 ] && shift
		LOG="$OUT/game-$DEMO.log"
		rm -f "$OUT"/floors-*.heights.new
		# a 1280x720-point window (2560x1440 pixels on a 2x display), the mouse never captured, muted, the radar on
		ARGS=(+set r_mode -1 +set r_customwidth 1280 +set r_customheight 720 +set r_fullscreen 0 +set r_noborder 0
			+set in_nograb 1 +set r_swapInterval 0 +set com_maxfpsUnfocused 0 +set com_maxfpsMinimized 0
			+set s_volume 0 +set s_musicvolume 0 +set cg_hudstyle 1 +set cg_hud_radar 1 +set nextdemo quit
			+set radarchk 1 +set radarchk_dump 1 "$@" +set timedemo 1 +demo "$DEMO")
		perl -e 'alarm shift; exec @ARGV' "${SECS:-300}" "$OMM_PORT/run.sh" radarchk "${ARGS[@]}" > "$LOG" 2>&1 || true
		checks=$(grep -a -c '^RADARCHK check' "$LOG" || true)
		bad=$(grep -a '^RADARCHK check' "$LOG" | grep -a -v -c ' differ 0$' || true)
		echo "radartest.sh game $DEMO: $checks pictures read back, $bad with a difference ($LOG); $(grep -a 'frames.*seconds' "$LOG" | tail -1)"
		[ "$checks" -gt 0 ] && [ "$bad" = 0 ]
		;;
	*)
		echo "usage: port/radartest.sh [alpha | lists [n] | real [file [heights]] | bench [file [heights]] | build | game [demo] [args]]" >&2
		exit 2
		;;
esac
